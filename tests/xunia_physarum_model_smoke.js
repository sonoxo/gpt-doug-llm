/* Offline Physarum model regression suite, no runtime dependencies. */
"use strict";
const assert=require("node:assert/strict");
const M=require("../docs/physarum/model.js");
const start=M.create();
assert.equal(start.schema,M.SCHEMA);
assert.equal(start.cols,18);
assert.equal(start.rows,12);
assert.equal(start.nodes.length,216);
assert.equal(start.edges.length,402);
assert.equal(start.food.length,2);
assert.equal(M.stats(start).ticks,0);
assert.equal(M.stats(start).active_tubes,0);
const before=M.stats(start),after=M.step(start,130);
assert.equal(after.ticks,130);
assert.ok(after.active_tubes>30,"Flow-induced tubes should reinforce");
assert.ok(after.total_abs_flux>0);
assert.ok(after.maximum_edge_flux>0);
assert.ok(after.flow_energy>0);
assert.equal(after.nutrient_count,2);
assert.ok(after.network_length_grid>before.network_length_grid);
assert.ok(start.edges.every(e=>Number.isFinite(e.d)&&Number.isFinite(e.q)&&e.d>=.015&&e.d<=3.5));
const network=M.network(start),out=JSON.stringify(network);
assert.equal(network.source_node,start.origin);
assert.equal(network.edges.length,402);
assert.equal(network.nodes.length,216);
assert.ok(out.includes("Physarum polycephalum"));
assert.ok(network.metrics.active_tubes>30);
const blueprint=M.svg(start);
assert.match(blueprint,/width="180mm" height="120mm"/);
assert.match(blueprint,/<path d=/);
assert.match(blueprint,/not organism growth map/);
assert.doesNotMatch(blueprint,/(script|foreignObject|onload=)/i);
const vectorEdges=(blueprint.match(/<path d=/g)||[]).length;
assert.ok(vectorEdges>10);
const clone=M.create();M.step(clone,130);
assert.deepEqual(M.network(start),M.network(clone),"simulation must be deterministic");
const id=M.nearest(start,9,6),edge=M.nearest(start,9,7);
assert.equal(M.barrier(start,id,true),true);
M.step(start,3);
assert.equal(start.nodes[id].blocked,true);
assert.ok(start.edges.filter(e=>e.a===id||e.b===id).every(e=>e.q===0));
assert.equal(M.network(start).edges.length,398,"Barriers must remove four conducting neighbors");
assert.equal(M.barrier(start,id,false),true);
assert.equal(M.addFood(start,edge),true);
assert.equal(M.stats(start).nutrient_count,3);
assert.equal(M.addFood(start,edge),true);
assert.equal(M.stats(start).nutrient_count,2);
assert.equal(M.barrier(start,start.origin,true),false);
assert.equal(M.addFood(start,start.origin),false);
assert.equal(M.setOrigin(start,start.food[0]),true);
assert.ok(start.food.length>0);
assert.ok(!start.food.includes(start.origin));
M.resetConductance(start);
assert.equal(start.tick,0);
assert.equal(M.stats(start).active_tubes,0);
assert.equal(start.nodes[id].blocked,false);
assert.equal(start.food.length,1);
assert.throws(()=>M.step(start,2001),/Step count/);
assert.throws(()=>M.create(2,5),/Grid bounds/);
console.log("CL1 PHYSARUM NODE TESTS PASS / adaptive tubes, source/sink pressure, barriers, SVG scale, deterministic export, reset");
