#!/usr/bin/env python3
"""Transfer only public OSIRIS feed-status metadata to local PINEAL memory.

This is intentionally NOT a live-position or CCTV ingestion connector. The
existing osiris_mirror module exclusively fetches allowlisted public routes.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import math
import os
from pathlib import Path
import re
import sys
import time
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SAFE_ROUTES = frozenset({
    "health", "earthquakes", "fires", "weather", "air-quality",
    "space-weather", "news", "live-news", "gdelt", "markets",
})
SOURCE_SCHEMA = "gpt-doug.osiris-safe-mirror.v1"
NAMESPACE = "osiris_feed"
SHA256 = re.compile(r"[0-9a-f]{64}\Z")


def records_from_snapshot(snapshot: dict[str, Any], now: float, max_age: int) -> list[dict[str, str]]:
    """Return bounded ontology records, never source payloads or coordinates."""
    if not isinstance(snapshot, dict) or snapshot.get("schema") != SOURCE_SCHEMA:
        raise ValueError("unrecognized OSIRIS snapshot schema")
    source = snapshot.get("source", {})
    if not isinstance(source, dict) or source.get("mode") != "authorized-public-safe-mirror":
        raise ValueError("snapshot was not generated by the authorized public mirror")
    states = snapshot.get("layer_state")
    if not isinstance(states, dict):
        raise ValueError("snapshot.layer_state must be an object")
    if type(max_age) is not int or not 60 <= max_age <= 86400:
        raise ValueError("max_age must be 60..86400 seconds")
    records: list[dict[str, str]] = []
    for route in sorted(set(states) & SAFE_ROUTES):
        entry = states[route]
        if not isinstance(entry, dict) or type(entry.get("ok")) is not bool:
            continue
        observed = entry.get("fetched_at")
        if not isinstance(observed, (int, float)) or isinstance(observed, bool):
            continue
        if not math.isfinite(observed) or observed <= 0:
            continue
        try:
            observed_iso = datetime.fromtimestamp(observed, tz=timezone.utc).isoformat()
        except (OSError, OverflowError, ValueError):
            # Untrusted local snapshot timestamps must not crash sync or invent freshness.
            continue
        age = now - float(observed)
        if age < -300:
            status = "CLOCK_SKEW"
        elif age > max_age:
            status = "STALE"
        elif entry["ok"]:
            status = "ONLINE"
        else:
            status = "DEGRADED"
        digest = entry.get("sha256")
        if not isinstance(digest, str) or not SHA256.fullmatch(digest):
            digest = None
        latency = entry.get("latency_ms")
        if not isinstance(latency, int) or isinstance(latency, bool) or not 0 <= latency <= 60000:
            latency = None
        details = {
            "route": route,
            "status": status,
            "last_check_utc": observed_iso,
            "sha256": digest,
            "latency_ms": latency,
            "provenance": "OSIRIS public route via gpt-doug.osiris-safe-mirror.v1",
            "raw_positions_or_camera_data_stored": False,
        }
        records.append({
            "subject": f"osiris:{route}",
            "predicate": "feed_health",
            "value": json.dumps(details, sort_keys=True, separators=(",", ":")),
        })
    return records


def sync_records(store: Any, records: list[dict[str, str]]) -> dict[str, int]:
    """Update an existing ontology triple only when its evidence changed."""
    created = updated = unchanged = 0
    for record in records:
        previous = store.search(namespace=NAMESPACE, subject=record["subject"], limit=10)
        match = next((item for item in previous if item.get("predicate") == "feed_health"), None)
        if match and match["value"] == record["value"]:
            unchanged += 1
            continue
        kwargs: dict[str, Any] = {
            **record,
            "namespace": NAMESPACE,
            "source": "osiris-safe-mirror-local-snapshot",
            "confidence": 1.0,
            "ttl_seconds": 86400,
            "actor": "pineal-osiris-bridge",
        }
        if match:
            kwargs["item_id"] = match["id"]
            kwargs["expected_version"] = match["version"]
            store.put(**kwargs)
            updated += 1
        else:
            store.put(**kwargs)
            created += 1
    return {"created": created, "updated": updated, "unchanged": unchanged}


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Import only OSIRIS safe-mirror metadata into local PINEAL")
    p.add_argument("--snapshot", type=Path, default=Path(os.getenv(
        "OSIRIS_MIRROR_OUT", str(Path.home() / ".local/share/gpt-doug/osiris-mirror"))) / "snapshot.json")
    p.add_argument("--pineal-home", type=Path, default=Path(os.getenv(
        "PINEAL_HOME", str(Path.home() / ".local/share/gpt-doug-pineal"))))
    p.add_argument("--max-age", type=int, default=600)
    p.add_argument("--dry-run", action="store_true", help="inspect local metadata without writing memory")
    args = p.parse_args(argv)
    path = args.snapshot.expanduser()
    if path.stat().st_size > 75_000_000:
        p.error("snapshot exceeds 75 MB limit")
    with path.open(encoding="utf-8") as fh:
        snapshot = json.load(fh)
    records = records_from_snapshot(snapshot, now=time.time(), max_age=args.max_age)
    if args.dry_run:
        print(json.dumps({"dry_run": True, "eligible_routes": [r["subject"] for r in records],
                          "writes": 0}, sort_keys=True))
        return 0
    sys.path.insert(0, str(ROOT / "integrations/gpt-doug-pineal/src"))
    from pineal.store import PinealStore
    store = PinealStore(args.pineal_home.expanduser() / "pineal.sqlite3")
    summary = sync_records(store, records)
    print(json.dumps({"schema": "gpt-doug.pineal-osiris-health.v1", "routes": len(records),
                      **summary, "audit": store.verify_audit()}, sort_keys=True))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"PINEAL OSIRIS import failed: {exc}", file=sys.stderr)
        sys.exit(2)
